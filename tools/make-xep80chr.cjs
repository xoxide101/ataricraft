// Builds web/js/xep80chr.js: a stand-in XEP80 character ROM image (2 sets x 256 chars x 16 bytes) derived from the
// NS405 internal font that ships inside atari800's xep80_fonts.c (GPL v2 or later). Characters 128-255 are the inverse.
// Usage: node tools/make-xep80chr.cjs
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'vendor/atari800/src/xep80_fonts.c'), 'utf8');
const start = src.indexOf('internal_font[');
const body = src.slice(src.indexOf('{', src.indexOf('=', start)), src.indexOf('};', start));
const rows = [...body.matchAll(/\{([01](?:,[01]){6})\}/g)].map((m) => m[1].split(',').map(Number));
if (rows.length !== 128 * 12) throw new Error('unexpected internal font size: ' + rows.length + ' rows');
const set = Buffer.alloc(256 * 16);
for (let c = 0; c < 128; c++) {
  for (let r = 0; r < 12; r++) {
    let b = 0;
    rows[c * 12 + r].forEach((v, i) => { if (v) b |= 0x80 >> i; });
    set[c * 16 + r] = b;
    set[(c + 128) * 16 + r] = ~b & 0xfe;
  }
}
const rom = Buffer.concat([set, set]);
const out = path.join(root, 'web/js/xep80chr.js');
fs.writeFileSync(out, '// Generated by tools/make-xep80chr.cjs from atari800 xep80_fonts.c (GPL v2 or later).\nwindow.AC = window.AC || {};\nAC.XEP80_CHR = "' + rom.toString('base64') + '";\n');
console.log('wrote', out, rom.length, 'bytes');
