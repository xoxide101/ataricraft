// Builds web/js/diskdb.js: CRC32 of the sector data of every ATR/XFD disk found under a folder (loose files and inside zips).
// Names come from the file names (TOSEC names are descriptive). Usage: node tools/make-diskdb.cjs <folder> [more folders...]
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const roots = process.argv.slice(2);
if (!roots.length) { console.error('usage: node tools/make-diskdb.cjs <folder>...'); process.exit(1); }
const db = {};
let seen = 0, dups = 0;

function add(name, buf) {
  let data = buf;
  if (buf.length > 16 && buf[0] === 0x96 && buf[1] === 0x02) data = buf.subarray(16);
  if (data.length < 90000 || data.length > 1500000) return;
  const crc = (zlib.crc32(data) >>> 0).toString(16).padStart(8, '0');
  seen++;
  const title = name.replace(/\.(atr|xfd)$/i, '');
  if (db[crc]) { dups++; return; }
  db[crc] = title;
}

function zipEntries(buf, cb) {
  let e = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 66000); i--) if (buf.readUInt32LE(i) === 0x06054b50) { e = i; break; }
  if (e < 0) return;
  const count = buf.readUInt16LE(e + 10);
  let p = buf.readUInt32LE(e + 16);
  for (let i = 0; i < count && buf.readUInt32LE(p) === 0x02014b50; i++) {
    const method = buf.readUInt16LE(p + 10), csize = buf.readUInt32LE(p + 20);
    const nl = buf.readUInt16LE(p + 28), xl = buf.readUInt16LE(p + 30), cl = buf.readUInt16LE(p + 32);
    const off = buf.readUInt32LE(p + 42);
    const name = buf.toString('utf8', p + 46, p + 46 + nl);
    p += 46 + nl + xl + cl;
    if (!/\.(atr|xfd)$/i.test(name)) continue;
    const s = off + 30 + buf.readUInt16LE(off + 26) + buf.readUInt16LE(off + 28);
    const raw = buf.subarray(s, s + csize);
    try { cb(path.basename(name), method === 0 ? raw : zlib.inflateRawSync(raw)); } catch (_) { }
  }
}

function walk(dir) {
  let items;
  try { items = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return; }
  for (const it of items) {
    const f = path.join(dir, it.name);
    if (it.isDirectory()) walk(f);
    else if (/\.(atr|xfd)$/i.test(it.name)) { try { add(it.name, fs.readFileSync(f)); } catch (_) { } }
    else if (/\.zip$/i.test(it.name)) {
      try { if (fs.statSync(f).size < 400e6) zipEntries(fs.readFileSync(f), add); } catch (_) { }
    }
  }
}

roots.forEach(walk);
const out = '// Generated by tools/make-diskdb.cjs from a local library: CRC32 of ATR/XFD sector data -> disk name.\n' +
  'window.AC = window.AC || {};\nAC.DISK_DB = ' + JSON.stringify(db) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'web', 'js', 'diskdb.js'), out);
console.log('disks hashed:', seen, 'unique:', Object.keys(db).length, 'duplicates:', dups, 'bytes:', out.length);
