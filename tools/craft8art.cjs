const G = require('./acwriter/font8z_art.cjs').T;

function face() {
  const f = CF.createSize(8, { name: 'Craft 8x8' });
  for (const [ch, def] of Object.entries(G)) {
    const [top, ...rows] = def, w = rows[0] ? rows[0].length : 0, g = new Array(f.rows).fill(0);
    if (rows.some((r) => r.length !== w)) throw new Error('8x8 glyph ' + ch + ': rows differ in width');
    const off = Math.floor((8 - w) / 2);
    rows.forEach((s, i) => { if (top + i > 7) throw new Error('8x8 glyph ' + ch + ' too tall'); for (let q = 0; q < w; q++) if (s[q] === '#') g[f.head + top + i] = CF.setPx(f, g[f.head + top + i], off + q); });
    f.glyphs[ch.charCodeAt(0)] = g;
  }
  return f;
}
module.exports = { face, GLYPHS: G };
