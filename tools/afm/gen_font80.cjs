const planes = [[], [], [], [], []];
for (let c = 0x20; c < 0x60; c++) {
  const g = G[String.fromCharCode(c)];
  if (!g) throw new Error('missing glyph ' + c);
  g.split('|').forEach((row, r) => planes[r].push(parseInt(row.replace(/#/g, '1').replace(/\./g, '0'), 2)));
}
let out = '; generated by gen_font80.cjs - do not edit\n';
planes.forEach((p, r) => {
  out += 'f80_' + r + ':\n';
  for (let i = 0; i < 64; i += 16) out += '        .byte ' + p.slice(i, i + 16).join(',') + '\n';
});
require('fs').writeFileSync(__dirname + '/font80.inc', out);
