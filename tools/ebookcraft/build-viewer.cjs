// Assembles viewer.asm (boot + XEX variants) with MADS and writes web/js/ebookcraft/ebc-viewer-data.js (base64).
// Usage: node tools/ebookcraft/build-viewer.cjs [path-to-mads.exe]
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const root = path.join(__dirname, '..', '..');
const mads = process.argv[2] || path.join(root, 'out', 'mads', 'mads.exe');
const src = path.join(__dirname, 'viewer.asm');
const outDir = path.join(root, 'out');
fs.mkdirSync(outDir, { recursive: true });
const res = {};
for (const x of [0, 1]) {
  const o = path.join(outDir, 'ebc-viewer' + x + '.bin');
  const r = cp.spawnSync(mads, [src, '-d:XEX=' + x, '-o:' + o], { encoding: 'utf8' });
  if (r.status !== 0 || !fs.existsSync(o)) { console.error(r.stdout, r.stderr); process.exit(1); }
  res[x ? 'xex' : 'boot'] = fs.readFileSync(o).toString('base64');
}
const js = '// GENERATED by tools/ebookcraft/build-viewer.cjs from tools/ebookcraft/viewer.asm - do not edit.\n' +
  '(function (G) { const EBC = G.EBC = G.EBC || {}; EBC.viewerData = ' + JSON.stringify(res) + ';\n' +
  "if (typeof module !== 'undefined') module.exports = EBC; })(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(root, 'web', 'js', 'ebookcraft', 'ebc-viewer-data.js'), js);
console.log('viewer boot', Buffer.from(res.boot, 'base64').length, 'xex', Buffer.from(res.xex, 'base64').length);
