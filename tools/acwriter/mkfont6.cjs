// Builds the 5x7 bar font (6px pitch, ASCII 32..127, 8 bytes per glyph, pixels in bits 7..3)
// from the 8x8 Atari font and writes font6.inc.
const fs = require('fs');
const fnt = fs.readFileSync(__dirname + '/../../web/library/fonts/atari/AtariPixel8.fnt');

function glyph(a) {
  const sc = a < 32 ? a + 64 : a < 96 ? a - 32 : a;
  let r = Array.from(fnt.slice(sc * 8, sc * 8 + 8));
  const desc = r[7] !== 0;
  r = desc ? r.slice(1, 8) : r.slice(0, 7);
  r.push(0);
  return r.map((b) => {
    const c = (k) => (b >> (7 - k)) & 1;
    const o = [c(0) | c(1), c(2), c(3), c(4), c(5) | c(6)];
    return (o[0] << 7) | (o[1] << 6) | (o[2] << 5) | (o[3] << 4) | (o[4] << 3);
  });
}

let out = '; generated by mkfont6.cjs - do not edit\n';
for (let a = 32; a < 128; a++) out += '        .byte ' + glyph(a).join(',') + '\n';
fs.writeFileSync(__dirname + '/font6.inc', out);
console.log('ok');
