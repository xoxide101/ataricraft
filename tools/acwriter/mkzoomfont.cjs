// Builds zfont.inc: the Craft 8x8 face (tools/craft8art.cjs, the same data as font/craft8.fnt) for the PAGE 2x zoom (word/zoom.inc).
// 96 glyphs, codes 32..127, 8 rows each, bit 7 = leftmost pixel. Code 127 is drawn as '?'.
const fs = require('fs');
const art = require('../craft8art.cjs');
const rows = (ch) => {
  const e = art.GLYPHS[ch], out = new Array(8).fill(0);
  if (!e) return out;
  const [top, ...r] = e, w = r[0] ? r[0].length : 0, off = Math.floor((8 - w) / 2);
  r.forEach((s, i) => { let v = 0; for (let q = 0; q < w; q++) if (s[q] === '#') v |= 0x80 >> (off + q); out[top + i] = v; });
  return out;
};
const all = [];
for (let a = 32; a <= 127; a++) all.push(...rows(a === 127 ? '?' : String.fromCharCode(a)));
let s = '; generated by mkzoomfont.cjs from tools/craft8art.cjs - do not edit\nzfont:\n';
for (let i = 0; i < all.length; i += 16) s += '        .byte ' + all.slice(i, i + 16).join(',') + '\n';
fs.writeFileSync(__dirname + '/zfont.inc', s);
console.log('zfont.inc', all.length, 'bytes');
