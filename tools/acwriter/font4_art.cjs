// 7 nibbles per glyph, bit 3 = leftmost pixel
function glyph(ch) {
  const def = A[ch];
  if (!def) return null;
  const out = new Array(7).fill(0), [top, ...rows] = def;
  rows.forEach((s, i) => {
    if (s.length !== 4 || top + i > 6) throw new Error('font4 art ' + ch + ' bad row ' + i);
    out[top + i] = [...s].reduce((n, c) => (n << 1) | (c === '#' ? 1 : 0), 0);
  });
  return out;
}
const OVR = {};
for (let a = 32; a < 127; a++) OVR[a] = glyph(String.fromCharCode(a));
OVR[127] = new Array(7).fill(0);
module.exports = OVR;
