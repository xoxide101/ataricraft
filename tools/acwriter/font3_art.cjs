// -> { ch: [top, ...rows] } for codes 32..126
function glyphTable() {
  const t = {};
  for (const ch of Object.keys(SK)) t[ch] = [2, ...(EXPLICIT7[ch] || stretch(SK[ch]))];
  for (const ch of Object.keys(OTHER)) t[ch] = OTHER[ch];
  return t;
}

const bits = (s) => [...s].reduce((v, c, q) => (c === '#' ? v | q + 1 : v), 0);

// 12 row array (bit q of each row = column q from the left) for one glyph
function cellRows(spec) {
  const out = new Array(12).fill(null).map(() => []);
  spec.slice(1).forEach((s, i) => { out[spec[0] + i] = [...s].map((c) => c === '#'); });
  return out;
}

// sup/sub 5-row form: rows index list on the 12-row cell
function smallRows(rows12, at) {
  const ink = (r) => rows12[r] && rows12[r].some(Boolean);
  const idx = ink(2) || ink(3) ? [2, 3, 5, 6, 8] : [4, 5, 6, 7, 8];
  const out = new Array(12).fill(null).map(() => []);
  idx.forEach((r, i) => { out[at + i] = rows12[r] || []; });
  return out;
}

function face() {
  const f = CF.createSize(4, { name: 'Craft 4x7' });
  const put = (rows12) => rows12.map((r) => { let v = 0; r.forEach((on, q) => { if (on) v = CF.setPx(f, v, q); }); return v; });
  const tab = glyphTable();
  for (let a = 32; a <= 126; a++) {
    const spec = tab[String.fromCharCode(a)];
    if (!spec) throw new Error('missing glyph ' + a + ' ' + String.fromCharCode(a));
    const rows12 = cellRows(spec);
    f.glyphs[a] = put(rows12);
    if (spec.length > 1) {
      f.sup[a] = put(smallRows(rows12, 0));
      f.sub[a] = put(smallRows(rows12, 6));
    }
  }
  f.glyphs[127] = new Array(12).fill(0);
  return f;
}

