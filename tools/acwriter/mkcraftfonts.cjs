// Builds the built-in Craft fonts (docs/FONT.md) from the Atari 8x8 font + the hand-tuned 4x7 glyphs:
//   web/library/fonts/craft/craft4.acf (4 px advance, 3 px glyph), craft5.acf (5 / 4), craft6.acf (6 / 5)
//   tools/acwriter/craft5.inc, craft6.inc, craft4.inc (6502 planes, prefix c4 / c5 / c6)
// Usage: node tools/acwriter/mkcraftfonts.cjs
const fs = require('fs');
const CF = require('../craftfont.cjs');
const R = __dirname + '/../../';
const fnt = fs.readFileSync(R + 'web/library/fonts/atari/AtariPixel8.fnt');
const f4 = JSON.parse(fs.readFileSync(__dirname + '/font4.json', 'utf8'));
const dir = R + 'web/library/fonts/craft/';
fs.mkdirSync(dir, { recursive: true });
const embed = {};
for (const adv of [4, 5, 6]) {
  const f = CF.builtin(fnt, adv, adv === 5 ? f4 : null);
  fs.writeFileSync(dir + 'craft' + adv + '.acf', CF.serialize(f));
  fs.writeFileSync(__dirname + '/craft' + adv + '.inc', CF.toInc(f, 'c' + adv));
  embed['craft' + adv] = CF.serialize(f).toString('base64');
  console.log('craft' + adv, CF.serialize(f).length, 'bytes');
}
fs.mkdirSync(R + 'web/js/fontedit', { recursive: true });
fs.writeFileSync(R + 'web/js/fontedit/builtin-fonts.js', '// GENERATED by tools/acwriter/mkcraftfonts.cjs - built-in Craft fonts (ACF2, base64).\nwindow.CRAFT_FONTS = ' + JSON.stringify(embed) + ";\n");
