// Builds craftpg.inc: the 3 px Craft font (craft4.inc) in the layout the PAGE mode blitter uses.
//   planes pwp2..pwp8 = glyph rows 2..8 (cap line .. baseline), 96 bytes each for codes 32..127
//   pwtix = per glyph: 0 (no descender rows) or offset+1 into pwtl, which holds rows 9..11 (3 bytes per entry)
// Blocks are laid out one after another inside the page-mode area (poc5.asm).
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'craft4.inc'), 'latin1').split(/\r?\n/);
const planes = {};
let cur = null;
for (const l of src) {
  const m = /^c4_(\d+):/.exec(l);
  if (m) { cur = +m[1]; planes[cur] = []; continue; }
  if (/^\w+:/.test(l)) { cur = null; continue; }
  const b = /^\s*\.byte\s+(.*)$/.exec(l);
  if (b && cur !== null) planes[cur].push(...b[1].split(',').map(s => +s.trim()));
}
for (let r = 0; r < 12; r++) if (planes[r].length !== 96) throw new Error('plane ' + r + ' has ' + planes[r].length);
for (let r = 0; r < 12; r++) for (const v of planes[r]) if (v & 0x1f) throw new Error('glyph wider than 3 px in plane ' + r);
const tix = new Array(96).fill(0), tl = [];
for (let g = 0; g < 96; g++) {
  const t = [planes[9][g], planes[10][g], planes[11][g]];
  if (t.some(v => v)) { tix[g] = tl.length + 1; tl.push(...t); }
}
const bytes = (a) => { const o = []; for (let i = 0; i < a.length; i += 16) o.push('        .byte ' + a.slice(i, i + 16).join(',')); return o.join('\n'); };
const block = (org, label, a, note) => `; ${note}\n${label}:\n${bytes(a)}\n`;
let out = '; generated by mkpgfont.cjs from craft4.inc - do not edit\n';
out += `pw_TAILS = ${tl.length / 3}\n`;
out += block('$9B00', 'pwp2', planes[2], 'row 2 (cap line)') + block('', 'pwp3', planes[3], 'row 3');
out += `pwtl:\n${bytes(tl)}\n`;
out += block('$9E90', 'pwp4', planes[4], 'row 4 (x-height)') + block('', 'pwp5', planes[5], 'row 5');
out += `pwtix:\n${bytes(tix)}\n`;
out += block('$BE60', 'pwp6', planes[6], 'row 6') + block('', 'pwp7', planes[7], 'row 7') + block('', 'pwp8', planes[8], 'row 8 (baseline)');
fs.writeFileSync(path.join(__dirname, 'craftpg.inc'), out);
const withTail = 'gjpqy,;()[]{}|/_@Q'.split('').filter(c => tix[c.charCodeAt(0) - 32]);
console.log('craftpg.inc written; tails for', tl.length / 3, 'glyphs:', withTail.join(''));
for (const c of '[]|+.:!LCR^<>0123456789') if (tix[c.charCodeAt(0) - 32]) console.log('note: ruler char with tail:', c);
