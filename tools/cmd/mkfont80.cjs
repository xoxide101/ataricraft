// lowercase: 3 row bodies sit on the baseline, 5 row letters have ascenders, 'd' letters hang below it
const low = {
  a: ['.##/#.#/.##'], b: '#../##./#.#/#.#/##.', c: ['.##/#../.##'], d: '..#/.##/#.#/#.#/.##',
  e: ['##./###/.##'], f: '.##/#../##./#../#..', g: ['.##/#.#/.##/..#/##.', 'd'], h: '#../##./#.#/#.#/#.#',
  i: '.#./.../.#./.#./.#.', j: '..#/.../..#/#.#/.#.', k: '#../#.#/##./#.#/#.#', l: '##./.#./.#./.#./.##',
  m: ['###/###/#.#'], n: ['##./#.#/#.#'], o: ['.#./#.#/.#.'], p: ['##./#.#/##./#../#..', 'd'],
  q: ['.##/#.#/.##/..#/..#', 'd'], r: ['.##/#../#..'], s: ['.##/.#./##.'], t: '.#./###/.#./.#./.##',
  u: ['#.#/#.#/###'], v: ['#.#/#.#/.#.'], w: ['#.#/###/###'], x: ['#.#/.#./#.#'],
  y: ['#.#/#.#/.##/..#/##.', 'd'], z: ['##./.#./.##'],
};
const word = (s, shift) => {
  const rows = s.split('/');
  while (rows.length < 5) rows.unshift('...');
  let v = 0;
  for (const r of rows) for (const c of r) v = (v << 1) | (c === '#' ? 1 : 0);
  return v | (shift ? 0x8000 : 0);
};
let out = '; generated by mkfont80.cjs - 3x5 glyphs, ASCII 32..126\r\n';
for (let c = 32; c < 127; c++) {
  const ch = String.fromCharCode(c);
  let w;
  if (ch >= 'a' && ch <= 'z') {
    const e = low[ch];
    w = typeof e === 'string' ? word(e, false) : word(e[0], e[1] === 'd');
  } else w = word(G[ch] || blank, false);
  out += `        dta a($${w.toString(16).toUpperCase().padStart(4, '0')})   ; ${ch}\r\n`;
}
fs.writeFileSync(path.join(__dirname, 'lib', 'font80.inc'), out);
