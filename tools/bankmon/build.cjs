// Builds BANKMON twice (bases $0000-relative pages 6 and 7) and writes web/js/bankmon.js with the code and a fixup list,
// so the Inspector can relocate it to any free page. Run: node tools/bankmon/build.cjs
const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const mads = path.join(root, 'out', 'mads', 'mads.exe');
const asm = (base) => {
  const out = path.join(__dirname, 'bm' + base.toString(16) + '.bin');
  execFileSync(mads, ['bankmon.asm', '-d:BASE=$' + base.toString(16), '-o:' + out], { cwd: __dirname, stdio: 'pipe' });
  const b = fs.readFileSync(out); fs.unlinkSync(out); return b;
};
const a = asm(0x0600), b = asm(0x0700);
if (a.length !== b.length) throw new Error('size mismatch');
const fix = [];
for (let i = 0; i < a.length; i++) {
  if (a[i] === b[i]) continue;
  if (b[i] !== a[i] + 1) throw new Error('unexpected difference at ' + i);
  fix.push(i);
}
const vbi = 0xD0; // entry offset, checked below
const src = `// Generated by tools/bankmon/build.cjs from tools/bankmon/bankmon.asm. Do not edit.
(function () {
  window.AC = window.AC || {};
  AC.BankMon = { base: 0x0600, entry: ${vbi}, fix: ${JSON.stringify(fix)}, code: '${a.toString('base64')}' };
})();
`;
module.exports = { a, fix, src };
if (require.main === module) {
  // locate the vbi entry: the first "LDA abs" (AD) after the tables, i.e. the byte at 0xD0
  if (a[vbi] !== 0xAD) throw new Error('entry not at +$D0 (found $' + a[vbi].toString(16) + ')');
  fs.writeFileSync(path.join(root, 'web', 'js', 'bankmon.js'), src);
  console.log('ok   bankmon.js', a.length, 'bytes,', fix.length, 'fixups');
}
