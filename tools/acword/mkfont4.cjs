// Builds a 4x7 glyph set (ASCII 32..127) from the 8x8 Atari font and writes font4.inc
// (seven planes f4_0..f4_6, 96 entries each, 4-bit values, bit 3 = leftmost pixel).
// Usage: node tools/acword/mkfont4.cjs [preview.png-data-out]
const fs = require('fs');
const R = __dirname + '/../../';
const fnt = fs.readFileSync(R + 'web/library/fonts/atari/AtariPixel8.fnt');
const OVR = require('./font4_fix.cjs');

function rows8(a) {
  const sc = a < 32 ? a + 64 : a < 96 ? a - 32 : a;
  return Array.from(fnt.slice(sc * 8, sc * 8 + 8));
}

// 8x8 (glyph in bits 7..2, 6 usable columns) -> 4 columns x 7 rows
function down(a) {
  let r = rows8(a);
  const desc = r[7] !== 0;
  r = desc ? r.slice(1, 8) : r.slice(0, 7);
  return r.map((b) => {
    const px = [];
    for (let c = 0; c < 6; c++) px.push((b >> (7 - c)) & 1);
    // 6 -> 4: columns (0,1) (2) (3) (4,5)
    const o = [px[0] | px[1], px[2], px[3], px[4] | px[5]];
    return (o[0] << 3) | (o[1] << 2) | (o[2] << 1) | o[3];
  });
}

const glyphs = [];
for (let a = 32; a < 128; a++) glyphs.push(OVR[a] || down(a));
let out = '; generated by mkfont4.cjs - do not edit\n';
for (let p = 0; p < 7; p++) {
  out += `f4_${p}:\n`;
  for (let i = 0; i < 96; i += 16) out += '        .byte ' + glyphs.slice(i, i + 16).map((g) => g[p]).join(',') + '\n';
}
fs.writeFileSync(__dirname + '/font4.inc', out);
fs.writeFileSync(__dirname + '/font4.json', JSON.stringify(glyphs));
console.log('ok', glyphs.length);
