// The 12x12 master: 12 cell, 10 ink columns (docs/FONT.md).
function master() {
  const f = CF.createSize(12, { name: 'Craft 12x12' });
  for (const [ch, def] of Object.entries(G)) {
    const [top, ...rows] = def, w = rows[0].length;
    if (rows.some((r) => r.length !== w)) throw new Error('glyph ' + ch + ': rows differ in width');
    if (w > f.gw) throw new Error('glyph ' + ch + ' wider than ' + f.gw);
    const off = Math.floor((f.gw - w) / 2), g = new Array(f.rows).fill(0);
    rows.forEach((s, i) => {
      if (top + i >= f.rows) throw new Error('glyph ' + ch + ' runs below the cell');
      for (let q = 0; q < w; q++) if (s[q] === '#') g[top + i] |= 0x8000 >> (off + q);
    });
    f.glyphs[ch.charCodeAt(0)] = g;
  }
  return f;
}

module.exports = { master, GLYPHS: G };
