/* Small Atari-style BASIC runtime for DOS (Open Watcom, 16-bit large model).
   Text, numbers, strings, arrays, FOR/NEXT, GOSUB, IF/THEN, INPUT, READ/DATA.
   No graphics, sound, PEEK/POKE or machine code. The program source is
   compiled in through prog.h (generated by scripts/build-basic-exe.cjs --dos). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include <math.h>
#include "prog.h"

#define MAXL 1500
#define MAXV 200
#define SLEN 255

typedef struct { int str; double n; char s[SLEN + 1]; } Val;
typedef struct { int num; const char *t; } Line;
typedef struct { char name[24]; double n; char *s; double *a; int d1, d2; int slen; } Var;
typedef struct { int li; const char *pos; Var *v; double end, step; } ForE;

static Line L[MAXL]; static int nl;
static Var V[MAXV]; static int nv;
static ForE F[16]; static int nf;
static int G[32]; static const char *GP[32]; static int ng;
static int li; static const char *p; static int running = 1, jumped;
static int dli = 0; static const char *dp = 0;

static void die(int code) {
  printf("\nERROR %d", code);
  if (li >= 0 && li < nl) printf(" AT LINE %d", L[li].num);
  printf("\n"); exit(1);
}
static void sp(void) { while (*p == ' ') p++; }
static int kw(const char *k) {
  int n = strlen(k); sp();
  if (strnicmp(p, k, n) == 0) { p += n; return 1; }
  return 0;
}
static Var *var(const char *name, int create) {
  int i;
  for (i = 0; i < nv; i++) if (!strcmp(V[i].name, name)) return &V[i];
  if (!create || nv >= MAXV) return 0;
  memset(&V[nv], 0, sizeof(Var)); strcpy(V[nv].name, name);
  return &V[nv++];
}
static int getname(char *out) {
  int n = 0; sp();
  if (!isalpha((unsigned char)*p)) return 0;
  while (isalnum((unsigned char)*p) && n < 20) out[n++] = toupper(*p++);
  if (*p == '$') out[n++] = *p++;
  out[n] = 0; return 1;
}
static Val expr(void);
static Val orexp(void);

static Val vnum(double n) { Val v; v.str = 0; v.n = n; v.s[0] = 0; return v; }
static Val vstr(const char *s) { Val v; v.str = 1; v.n = 0; strncpy(v.s, s, SLEN); v.s[SLEN] = 0; return v; }
static double num(Val v) { if (v.str) die(8); return v.n; }

static void fmtnum(double d, char *o) {
  if (d == floor(d) && fabs(d) < 1e9) sprintf(o, "%ld", (long)d);
  else sprintf(o, "%.9g", d);
}
static Val arg(void) { Val v; sp(); if (*p != '(') die(8); p++; v = expr(); sp(); if (*p != ')') die(8); p++; return v; }
static int idx(void) { return (int)num(expr()); }

static Val func(const char *n) {
  Val a, r; char buf[40]; int i, j;
  if (!strcmp(n, "LEFT$") || !strcmp(n, "RIGHT$") || !strcmp(n, "MID$")) {
    sp(); p++; a = expr(); sp(); if (*p++ != ',') die(8); i = idx(); j = -1;
    sp(); if (*p == ',') { p++; j = idx(); } sp(); if (*p == ')') p++;
    if (!a.str) die(8);
    r = vstr("");
    if (n[0] == 'L') { if (i > 0) { strncpy(r.s, a.s, i); r.s[i < SLEN ? i : SLEN] = 0; } }
    else if (n[0] == 'R') { int l = strlen(a.s); strcpy(r.s, a.s + (i < l ? l - i : 0)); }
    else { int l = strlen(a.s); if (i < 1) i = 1; if (i <= l) { strcpy(r.s, a.s + i - 1); if (j >= 0) r.s[j] = 0; } }
    return r;
  }
  a = arg();
  if (!strcmp(n, "INT")) return vnum(floor(num(a)));
  if (!strcmp(n, "ABS")) return vnum(fabs(num(a)));
  if (!strcmp(n, "SQR")) return vnum(sqrt(num(a)));
  if (!strcmp(n, "SGN")) return vnum(num(a) > 0 ? 1 : num(a) < 0 ? -1 : 0);
  if (!strcmp(n, "SIN")) return vnum(sin(num(a)));
  if (!strcmp(n, "COS")) return vnum(cos(num(a)));
  if (!strcmp(n, "ATN")) return vnum(atan(num(a)));
  if (!strcmp(n, "LOG")) return vnum(log(num(a)));
  if (!strcmp(n, "CLOG")) return vnum(log10(num(a)));
  if (!strcmp(n, "EXP")) return vnum(exp(num(a)));
  if (!strcmp(n, "RND")) return vnum(rand() / 32768.0);
  if (!strcmp(n, "LEN")) { if (!a.str) die(8); return vnum(strlen(a.s)); }
  if (!strcmp(n, "ASC")) { if (!a.str) die(8); return vnum((unsigned char)a.s[0]); }
  if (!strcmp(n, "VAL")) { if (!a.str) die(8); return vnum(atof(a.s)); }
  if (!strcmp(n, "CHR$")) { buf[0] = (char)(int)num(a); buf[1] = 0; return vstr(buf); }
  if (!strcmp(n, "STR$")) { fmtnum(num(a), buf); return vstr(buf); }
  if (!strcmp(n, "PEEK") || !strcmp(n, "FRE") || !strcmp(n, "ADR") || !strcmp(n, "USR")) return vnum(0);
  die(17); return vnum(0);
}

static Val primary(void) {
  Val v; char nm[24]; Var *x; sp();
  if (*p == '(') { p++; v = orexp(); sp(); if (*p == ')') p++; return v; }
  if (*p == '"') {
    int n = 0; p++;
    while (*p && *p != '"') { if (n < SLEN) v.s[n++] = *p; p++; }
    v.s[n] = 0; if (*p == '"') p++; v.str = 1; v.n = 0; return v;
  }
  if (*p == '-') { p++; return vnum(-num(primary())); }
  if (*p == '+') { p++; return primary(); }
  if (isdigit((unsigned char)*p) || *p == '.') { char *e; double d = strtod(p, &e); p = e; return vnum(d); }
  if (kw("NOT")) return vnum(num(primary()) == 0);
  if (getname(nm)) {
    if (nm[strlen(nm) - 1] == '$' && strcmp(nm, "LEFT$") && strcmp(nm, "RIGHT$") && strcmp(nm, "MID$") && strcmp(nm, "CHR$") && strcmp(nm, "STR$")) {
      x = var(nm, 1); sp();
      if (*p == '(') {
        int a, b; p++; a = idx(); sp(); b = a;
        if (*p == ',') { p++; b = idx(); } sp(); if (*p == ')') p++;
        if (!x->s) die(9);
        if (a < 1 || b > x->slen || b < a - 1) die(5);
        { int n = b - a + 1; memcpy(v.s, x->s + a - 1, n); v.s[n] = 0; v.str = 1; v.n = 0; return v; }
      }
      if (!x->s) die(9);
      return vstr(x->s);
    }
    sp();
    if (*p == '(') {
      x = var(nm, 0);
      if (x && x->a) {
        int a, b = 0; p++; a = idx(); sp();
        if (*p == ',') { p++; b = idx(); } sp(); if (*p == ')') p++;
        if (a < 0 || a >= x->d1 || b < 0 || b >= (x->d2 ? x->d2 : 1)) die(9);
        return vnum(x->a[a * (x->d2 ? x->d2 : 1) + b]);
      }
      return func(nm);
    }
    if (!strcmp(nm, "RND")) return vnum(rand() / 32768.0);
    x = var(nm, 1);
    return vnum(x->n);
  }
  die(8); return vnum(0);
}
static Val power(void) { Val a = primary(); sp(); while (*p == '^') { p++; a = vnum(pow(num(a), num(primary()))); sp(); } return a; }
static Val term(void) {
  Val a = power(), b; sp();
  while (*p == '*' || *p == '/') {
    char o = *p++; b = power();
    if (o == '*') a = vnum(num(a) * num(b)); else { if (num(b) == 0) die(11); a = vnum(num(a) / num(b)); }
    sp();
  }
  return a;
}
static Val sum(void) {
  Val a = term(), b; sp();
  while (*p == '+' || *p == '-') {
    char o = *p++; b = term();
    if (o == '+' && a.str && b.str) { strncat(a.s, b.s, SLEN - strlen(a.s)); }
    else if (o == '+') a = vnum(num(a) + num(b)); else a = vnum(num(a) - num(b));
    sp();
  }
  return a;
}
static Val cmp(void) {
  Val a = sum(), b; int c;
  for (;;) {
    int op = 0; sp();
    if (p[0] == '<' && p[1] == '>') { op = 1; p += 2; }
    else if (p[0] == '<' && p[1] == '=') { op = 2; p += 2; }
    else if (p[0] == '>' && p[1] == '=') { op = 3; p += 2; }
    else if (*p == '<') { op = 4; p++; }
    else if (*p == '>') { op = 5; p++; }
    else if (*p == '=') { op = 6; p++; }
    else break;
    b = sum();
    if (a.str != b.str) die(8);
    c = a.str ? strcmp(a.s, b.s) : (a.n < b.n ? -1 : a.n > b.n ? 1 : 0);
    a = vnum(op == 1 ? c != 0 : op == 2 ? c <= 0 : op == 3 ? c >= 0 : op == 4 ? c < 0 : op == 5 ? c > 0 : c == 0);
  }
  return a;
}
static Val andexp(void) { Val a = cmp(); while (kw("AND")) { Val b = cmp(); a = vnum(num(a) != 0 && num(b) != 0); } return a; }
static Val orexp(void) { Val a = andexp(); while (kw("OR")) { Val b = andexp(); a = vnum(num(a) != 0 || num(b) != 0); } return a; }
static Val expr(void) { return orexp(); }

static int findline(int n) { int i; for (i = 0; i < nl; i++) if (L[i].num == n) return i; die(12); return 0; }
static void jump(int n) { li = findline(n); p = L[li].t; jumped = 1; }

static void dim1(char *nm, int a, int b) {
  Var *x = var(nm, 1);
  if (nm[strlen(nm) - 1] == '$') { x->s = (char *)calloc(a + 2, 1); x->slen = 0; x->d1 = a; }
  else { x->d1 = a + 1; x->d2 = b >= 0 ? b + 1 : 0; x->a = (double *)calloc(x->d1 * (x->d2 ? x->d2 : 1), sizeof(double)); }
}

static void setstr(Var *x, const char *s) {
  if (!x->s) die(9);
  strncpy(x->s, s, x->d1); x->s[x->d1] = 0; x->slen = strlen(x->s);
}

static void doinput(void) {
  char nm[24], buf[300]; Var *x; sp();
  if (*p == '"') { Val q = primary(); printf("%s", q.s); sp(); if (*p == ';' || *p == ',') p++; } else printf("? ");
  for (;;) {
    if (!getname(nm)) break;
    x = var(nm, 1); fflush(stdout);
    if (!fgets(buf, sizeof buf, stdin)) die(136);
    buf[strcspn(buf, "\r\n")] = 0;
    if (nm[strlen(nm) - 1] == '$') setstr(x, buf);
    else { char *e; x->n = strtod(buf, &e); if (e == buf) die(8); }
    sp(); if (*p == ',') p++; else break;
  }
}
static int nextdata(Val *out, int wantstr) {
  for (;;) {
    if (!dp) { while (dli < nl && strnicmp(L[dli].t, "DATA", 4)) dli++; if (dli >= nl) return 0; dp = L[dli].t + 4; }
    while (*dp == ' ') dp++;
    if (!*dp) { dp = 0; dli++; continue; }
    { char tmp[SLEN + 1]; int n = 0;
      if (*dp == '"') { dp++; while (*dp && *dp != '"') tmp[n++] = *dp++; if (*dp) dp++; }
      else while (*dp && *dp != ',') tmp[n++] = *dp++;
      tmp[n] = 0;
      while (n > 0 && tmp[n - 1] == ' ') tmp[--n] = 0;
      if (*dp == ',') dp++; else { dp = 0; dli++; }
      *out = wantstr ? vstr(tmp) : vnum(atof(tmp)); return 1; }
  }
}

static void print(void) {
  int nl_ = 1; sp();
  while (*p && *p != ':') {
    if (*p == ';') { p++; nl_ = 0; sp(); continue; }
    if (*p == ',') { p++; printf("\t"); nl_ = 0; sp(); continue; }
    { Val v = expr(); char b[40]; if (v.str) printf("%s", v.s); else { fmtnum(v.n, b); printf("%s", b); } nl_ = 1; }
    sp();
  }
  if (nl_) printf("\n");
}

static void assign(char *nm) {
  Var *x = var(nm, 1); int a = 0, b = 0, hasidx = 0, has2 = 0; Val v; sp();
  if (*p == '(') {
    hasidx = 1; p++; a = idx(); sp();
    if (*p == ',') { p++; b = idx(); has2 = 1; } sp(); if (*p == ')') p++; sp();
  }
  if (*p != '=') die(17); p++;
  v = expr();
  if (nm[strlen(nm) - 1] == '$') {
    if (!x->s) die(9);
    if (!v.str) die(8);
    if (hasidx) {
      int e = has2 ? b : x->slen, n = strlen(v.s);
      if (a < 1 || e > x->d1) die(5);
      while (x->slen < a - 1) x->s[x->slen++] = ' ';
      if (n > e - a + 1) n = e - a + 1;
      memcpy(x->s + a - 1, v.s, n);
      if (!has2 || a - 1 + n > x->slen) x->slen = a - 1 + n;
      x->s[x->slen] = 0;
    } else setstr(x, v.s);
  } else if (hasidx) {
    if (!x->a || a < 0 || a >= x->d1 || b < 0 || b >= (x->d2 ? x->d2 : 1)) die(9);
    x->a[a * (x->d2 ? x->d2 : 1) + b] = num(v);
  } else x->n = num(v);
}

static void skiptoend(void) { p += strlen(p); }

static void stmt(void) {
  char nm[24]; sp();
  if (!*p) return;
  if (kw("REM") || *p == '.') { skiptoend(); return; }
  if (kw("DATA")) { skiptoend(); return; }
  if (kw("PRINT") || (*p == '?' && p++)) { print(); return; }
  if (kw("INPUT")) { doinput(); return; }
  if (kw("LET")) { getname(nm); assign(nm); return; }
  if (kw("GOTO") || kw("GO TO")) { jump(idx()); return; }
  if (kw("GOSUB")) {
    int n = idx(); if (ng >= 32) die(2);
    G[ng] = li; GP[ng++] = p; jump(n); return;
  }
  if (kw("RETURN")) { if (!ng) die(16); ng--; li = G[ng]; p = GP[ng]; jumped = 1; return; }
  if (kw("END") || kw("STOP")) { running = 0; return; }
  if (kw("POP")) { if (ng) ng--; return; }
  if (kw("IF")) {
    Val c = expr(); kw("THEN");
    if (num(c) == 0) { skiptoend(); return; }
    sp();
    if (isdigit((unsigned char)*p)) { jump(idx()); return; }
    stmt(); return;
  }
  if (kw("FOR")) {
    Var *x; ForE *f; double e, s = 1;
    getname(nm); x = var(nm, 1); sp(); if (*p++ != '=') die(17);
    x->n = num(expr()); if (!kw("TO")) die(17); e = num(expr());
    if (kw("STEP")) s = num(expr());
    if (nf >= 16) die(2);
    f = &F[nf++]; f->li = li; f->pos = p; f->v = x; f->end = e; f->step = s; return;
  }
  if (kw("NEXT")) {
    ForE *f; int k; sp();
    if (getname(nm)) { for (k = nf - 1; k >= 0; k--) if (!strcmp(F[k].v->name, nm)) break; if (k < 0) die(13); nf = k + 1; }
    if (!nf) die(13);
    f = &F[nf - 1]; f->v->n += f->step;
    if ((f->step >= 0 && f->v->n <= f->end) || (f->step < 0 && f->v->n >= f->end)) { li = f->li; p = f->pos; jumped = 1; }
    else nf--;
    return;
  }
  if (kw("DIM") || kw("COM")) {
    for (;;) {
      int a, b = -1; if (!getname(nm)) break; sp();
      if (*p == '(') { p++; a = idx(); sp(); if (*p == ',') { p++; b = idx(); } sp(); if (*p == ')') p++; dim1(nm, a, b); }
      sp(); if (*p == ',') p++; else break;
    }
    return;
  }
  if (kw("READ")) {
    for (;;) {
      Val v; Var *x; if (!getname(nm)) break;
      x = var(nm, 1);
      if (!nextdata(&v, nm[strlen(nm) - 1] == '$')) die(6);
      if (nm[strlen(nm) - 1] == '$') setstr(x, v.s); else x->n = v.n;
      sp(); if (*p == ',') p++; else break;
    }
    return;
  }
  if (kw("RESTORE")) { sp(); dp = 0; dli = 0; if (isdigit((unsigned char)*p)) dli = findline(idx()); return; }
  if (kw("POKE") || kw("POSITION") || kw("GRAPHICS") || kw("COLOR") || kw("PLOT") || kw("DRAWTO") ||
      kw("SETCOLOR") || kw("SOUND") || kw("OPEN") || kw("CLOSE") || kw("TRAP") || kw("CLR") || kw("SAVE") || kw("LIST")) { skiptoend(); return; }
  if (getname(nm)) { assign(nm); return; }
  die(17);
}

static int cmpl(const void *a, const void *b) { return ((Line *)a)->num - ((Line *)b)->num; }

int main(void) {
  int i;
  for (i = 0; i < PROG_N; i++) { L[nl].num = prog_nums[i]; L[nl].t = prog_text[i]; nl++; }
  qsort(L, nl, sizeof(Line), cmpl);
  li = 0; if (nl) p = L[0].t;
  while (running && li < nl) {
    sp();
    if (!*p) { li++; if (li < nl) p = L[li].t; continue; }
    if (*p == ':') p++;
    jumped = 0; stmt();
    if (jumped) continue;
    sp();
    if (*p == ':') { p++; continue; }
    if (*p) die(17);
  }
  return 0;
}
