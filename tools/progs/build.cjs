// Bundles the stand-alone programs built in this repo into web/js/progs.js so the Inspector can run them from the page (no DOS disk needed).
// Usage: node tools/progs/build.cjs   (rebuild the sources first: node tools/net/build.cjs, tools/tests/build.cjs, ...)
const fs = require('fs'), path = require('path');
const T = path.join(__dirname, '..');
const LIST = [
  ['net/ping.com', 'PING', 'Network', 'Reachability test through the FujiNet N: device. Prompts for a host.'],
  ['net/nslookup.com', 'NSLOOKUP', 'Network', 'Resolve a host name to an address.'],
  ['net/tracert.com', 'TRACERT', 'Network', 'Trace the route to a host.'],
  ['net/whois.com', 'WHOIS', 'Network', 'WHOIS query for a domain.'],
  ['net/ipconfig.com', 'IPCONFIG', 'Network', 'Lists the PC network interfaces (IP and mask) as reported by the relay.'],
  ['tests/bin/CPUTEST.COM', 'CPUTEST', 'Self test', '6502 instruction and flag test.'],
  ['tests/bin/MEMTEST.COM', 'MEMTEST', 'Self test', 'Base RAM test.'],
  ['tests/bin/GFXTEST.COM', 'GFXTEST', 'Self test', 'Graphics modes and colour test.'],
  ['tests/bin/SNDTEST.COM', 'SNDTEST', 'Self test', 'POKEY sound test.'],
  ['tests/bin/KEYTEST.COM', 'KEYTEST', 'Self test', 'Keyboard and key code test.'],
  ['tui/tuidemo.com', 'TUIDEMO', 'Demo', 'Text-mode windows, menu bar and mouse pointer (tui.inc).'],
  ['cmd/bin/calc.com', 'CALC', 'Utility', 'Calculator.'],
  ['cmd/bin/80col.com', '80COL', 'Utility', '80-column text driver demo.'],
  ['afm/afm.com', 'AFM', 'Utility', 'Atari File Manager, 40 columns (needs a disk with files).'],
  ['afm/afm80.com', 'AFM80', 'Utility', 'Atari File Manager, 80 columns.'],
];
const out = LIST.map(([f, name, group, desc]) => ({ name, group, desc, file: path.basename(f).toUpperCase(), b64: fs.readFileSync(path.join(T, f)).toString('base64') }));
fs.writeFileSync(path.join(T, '..', 'web', 'js', 'progs.js'),
  '// Generated by tools/progs/build.cjs. Do not edit.\n(function () { window.AC = window.AC || {}; AC.Progs = ' + JSON.stringify(out) + '; })();\n');
console.log('progs.js', out.length, 'programs', out.reduce((s, p) => s + p.b64.length, 0), 'b64 chars');
