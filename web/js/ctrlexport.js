// Export a controller profile for other emulators: MAME ctrlr .cfg, RetroArch autoconfig .cfg and core remap .rmap, SDL gamecontrollerdb line.
// Formats were checked against the upstream sources (mamedev/mame src/emu/ioport.cpp, inpttype.ipp, input.cpp; libretro/RetroArch configuration.c and
// libretro-joypad-autoconfig; libsdl-org/SDL SDL_gamepad.c). Nothing here has been tried on the real Atari Gamestation Gamepad:
// every export is UNTESTED ON HARDWARE and is written into each file header.
(function (root, factory) {
  const api = factory(typeof module === 'object' && module.exports ? require('./ctrlcore.js') : root.AC.CtrlCore);
  if (typeof module === 'object' && module.exports) module.exports = api;
  else { root.AC = root.AC || {}; root.AC.CtrlExport = api; }
})(typeof window !== 'undefined' ? window : globalThis, function (Core) {
  const BANNER = 'UNTESTED ON HARDWARE: generated by Ataricraft for the Atari Gamestation Gamepad (DGUNL-7152) before the device was available. Verify every binding.';
  const slug = (s) => String(s || 'profile').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'profile';
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const first = (a) => (a && a[0]) || null;
  const ctl = (p, k) => (p.device.controls[k] || []);

  // ---- MAME ----
  const AXIS = ['XAXIS', 'YAXIS', 'ZAXIS', 'RXAXIS', 'RYAXIS', 'RZAXIS', 'SLIDER1', 'SLIDER2'];
  const HAT = { 12: 'HAT1UP', 13: 'HAT1DOWN', 14: 'HAT1LEFT', 15: 'HAT1RIGHT' };
  const KEYS = { Space: 'SPACE', Enter: 'ENTER', Escape: 'ESC', Tab: 'TAB', Backspace: 'BACKSPACE', Delete: 'DEL', ArrowUp: 'UP', ArrowDown: 'DOWN', ArrowLeft: 'LEFT', ArrowRight: 'RIGHT',
    ShiftLeft: 'LSHIFT', ShiftRight: 'RSHIFT', ControlLeft: 'LCONTROL', ControlRight: 'RCONTROL', AltLeft: 'LALT', AltRight: 'RALT',
    NumpadMultiply: 'ASTERISK', NumpadDivide: 'SLASHPAD', NumpadAdd: 'PLUSPAD', NumpadSubtract: 'MINUSPAD', NumpadEnter: 'ENTERPAD', NumpadDecimal: 'DELPAD',
    Minus: 'MINUS', Comma: 'COMMA', Period: 'STOP', Slash: 'SLASH', Quote: 'QUOTE', Semicolon: 'COLON', BracketLeft: 'OPENBRACE', BracketRight: 'CLOSEBRACE', Backquote: 'TILDE', Equal: 'EQUALS', Backslash: 'BACKSLASH' };
  function mameKey(code) {
    let m;
    if ((m = /^Key([A-Z])$/.exec(code))) return 'KEYCODE_' + m[1];
    if ((m = /^Digit(\d)$/.exec(code))) return 'KEYCODE_' + m[1];
    if ((m = /^Numpad(\d)$/.exec(code))) return 'KEYCODE_' + m[1] + 'PAD';
    if (/^F([1-9]|1[0-2])$/.test(code)) return 'KEYCODE_' + code;
    return KEYS[code] ? 'KEYCODE_' + KEYS[code] : null;
  }
  // digital source -> MAME code, or null when MAME has no equivalent
  function mameDigital(id, o) {
    let m;
    if ((m = /^gp:b(\d+)$/.exec(id))) return o.dpadAsHat && HAT[m[1]] ? `JOYCODE_${o.joy}_${HAT[m[1]]}` : `JOYCODE_${o.joy}_BUTTON${+m[1] + 1}`;
    if ((m = /^gp:a(\d+)([+-])$/.exec(id))) {
      const a = AXIS[+m[1]]; if (!a) return null;
      const side = a === 'XAXIS' ? (m[2] === '-' ? 'LEFT' : 'RIGHT') : a === 'YAXIS' ? (m[2] === '-' ? 'UP' : 'DOWN') : (m[2] === '-' ? 'NEG' : 'POS');
      return `JOYCODE_${o.joy}_${a}_${side}_SWITCH`;
    }
    if (id.startsWith('kb:')) return mameKey(id.slice(3));
    if ((m = /^ms:b(\d)$/.exec(id))) return `MOUSECODE_${o.mouse}_BUTTON${+m[1] + 1}`;
    return null;
  }
  function mameAnalog(id, o, rev) {
    let m, c = null;
    if ((m = /^gp:a(\d+)$/.exec(id)) && AXIS[+m[1]]) c = `JOYCODE_${o.joy}_${AXIS[+m[1]]}`;
    else if (id === 'ms:dx') c = `MOUSECODE_${o.mouse}_XAXIS`;
    else if (id === 'ms:dy') c = `MOUSECODE_${o.mouse}_YAXIS`;
    else if (id === 'ms:wheel') c = `MOUSECODE_${o.mouse}_ZAXIS`;
    return c && rev ? c + '_REVERSE' : c;
  }

  function mame(p, opts) {
    const o = Object.assign({ joy: 1, mouse: 1, dpadAsHat: p.device.mapping === 'standard' }, opts), notes = [], ports = new Map();
    const add = (type, kind, code) => { if (!code) return; const e = ports.get(type) || { standard: [], increment: [], decrement: [] }; if (!e[kind].includes(code)) e[kind].push(code); ports.set(type, e); };
    const dig = (type, ids, what) => { let n = 0; (ids || []).forEach((i) => { const c = mameDigital(i, o); if (c) { add(type, 'standard', c); n++; } else notes.push(`${what}: ${i} has no MAME code, skipped`); }); return n; };
    const J = p.joystick;
    if (J.enabled) {
      const t = 'P' + J.port + '_';
      dig(t + 'JOYSTICK_UP', J.up, 'joystick up'); dig(t + 'JOYSTICK_DOWN', J.down, 'joystick down'); dig(t + 'JOYSTICK_LEFT', J.left, 'joystick left'); dig(t + 'JOYSTICK_RIGHT', J.right, 'joystick right');
      dig(t + 'BUTTON1', J.fire, 'fire'); dig(t + 'BUTTON2', J.fire2, 'fire 2');
    }
    const D = p.paddle;
    if (D.enabled) {
      const t = 'P' + D.port + '_PADDLE';
      D.source.forEach((i) => { const c = mameAnalog(i, o, D.invert); if (c) add(t, 'standard', c); else notes.push(`paddle: ${i} has no MAME analog code, skipped`); });
      dig(t, [], ''); D.left.forEach((i) => add(t, 'decrement', mameDigital(i, o))); D.right.forEach((i) => add(t, 'increment', mameDigital(i, o)));
      dig('P' + D.port + '_BUTTON1', D.button, 'paddle button');
      notes.push('paddle: P' + D.port + '_PADDLE accumulates and clamps in MAME. Sensitivity, dead zone and auto-recentre are per-game settings in MAME and are not part of a ctrlr file.');
    }
    const S = p.spinner;
    if (S.enabled) {
      const t = 'P' + S.port + '_DIAL';
      S.source.forEach((i) => { const c = mameAnalog(i, o, S.invert); if (c) add(t, 'standard', c); else notes.push(`spinner: ${i} has no MAME analog code, skipped`); });
      dig('P' + S.port + '_BUTTON1', S.fire, 'spinner button');
      notes.push('spinner: P' + S.port + '_DIAL passes relative counts through (free-spinning 360 degree control).');
    }
    const T = p.trackball;
    if (T.enabled) {
      const t = 'P' + T.port + '_TRACKBALL_';
      const xs = T.swapXY ? T.y : T.x, ys = T.swapXY ? T.x : T.y;
      xs.forEach((i) => { const c = mameAnalog(i, o, T.invertX); if (c) add(t + 'X', 'standard', c); else notes.push(`trackball X: ${i} skipped`); });
      ys.forEach((i) => { const c = mameAnalog(i, o, T.invertY); if (c) add(t + 'Y', 'standard', c); else notes.push(`trackball Y: ${i} skipped`); });
      dig('P' + T.port + '_BUTTON1', T.fire, 'trackball fire');
    }
    // Console / front-panel buttons that have a generic MAME type (switches of a specific machine are per-driver ports and are not mapped).
    const startSrc = p.console.start.length ? p.console.start : ctl(p, 'START');
    const selSrc = p.console.select.length ? p.console.select : ctl(p, 'SELECT');
    if (p.console.enabled || startSrc.length) { dig('START1', startSrc, 'start'); dig('P1_SELECT', selSrc, 'select'); }
    dig('COIN1', ctl(p, 'CREDIT'), 'credit'); dig('UI_MENU', ctl(p, 'MENU'), 'menu');
    if (p.keypad.enabled) notes.push('keypad: MAME exposes the keypad only through machine-specific ports, so 0-9 * # are not written. Map them in MAME (Tab > Input) or use the keyboard.');
    notes.push('console OPTION/RESET have no generic MAME input type and are not written.');
    notes.push('Joystick button numbers and axis order are those of the browser Gamepad API; MAME numbers them by its own input provider (DirectInput/SDL), so they can differ. Use MAME\'s Tab > Input (This Machine) to confirm.');
    const L = ['<?xml version="1.0"?>', `<!-- ${BANNER} -->`, '<mameconfig version="10">', '\t<system name="default">', '\t\t<input>'];
    for (const [type, e] of ports) {
      const seqs = ['standard', 'increment', 'decrement'].filter((k) => e[k].length);
      if (!seqs.length) continue;
      L.push(`\t\t\t<port type="${esc(type)}">`);
      seqs.forEach((k) => L.push(`\t\t\t\t<newseq type="${k}">${esc(e[k].join(' OR '))}</newseq>`));
      L.push('\t\t\t</port>');
    }
    L.push('\t\t</input>', '\t</system>', '</mameconfig>', '');
    return { filename: slug(p.name) + '-mame.cfg', text: L.join('\n'), notes, mime: 'application/xml', hint: 'Save as ctrlr/<name>.cfg in the MAME folder and start MAME with -ctrlr <name>.' };
  }

  // ---- RetroArch autoconfig .cfg ----
  const RA_ROLES = [['b', 'B', 'B'], ['a', 'A', 'A'], ['x', 'X', 'X'], ['y', 'Y', 'Y'], ['l', 'L1', 'L1'], ['r', 'R1', 'R1'], ['l2', 'L2', 'L2'], ['r2', 'R2', 'R2'],
    ['select', 'SELECT', 'Select'], ['start', 'START', 'Start'], ['up', 'DPAD_UP', 'D-Pad Up'], ['down', 'DPAD_DOWN', 'D-Pad Down'], ['left', 'DPAD_LEFT', 'D-Pad Left'], ['right', 'DPAD_RIGHT', 'D-Pad Right'],
    ['menu_toggle', 'MENU', 'Menu'], ['l3', 'CREDIT', 'Credit'], ['r3', 'SETTINGS', 'Settings']];
  function raSource(p, phys) {
    const fb = { B: p.joystick.fire, A: p.joystick.fire2, START: p.console.start, SELECT: p.console.select, DPAD_UP: p.joystick.up, DPAD_DOWN: p.joystick.down, DPAD_LEFT: p.joystick.left, DPAD_RIGHT: p.joystick.right };
    return first(ctl(p, phys).length ? ctl(p, phys) : fb[phys] || []);
  }
  function retroarchCfg(p, opts) {
    const o = Object.assign({ driver: 'udev' }, opts), notes = [], L = [`# ${BANNER}`];
    const name = p.device.name || 'Atari Gamestation Gamepad';
    const vid = p.device.vendorId, pid = p.device.productId;
    if (vid === null || pid === null) { L.push('# TODO: vendor/product id unknown; connect the controller on the Controller page (WebHID or Gamepad) so they can be filled in.'); notes.push('vendor/product id not recorded: written as 0'); }
    if (p.device.mapping === 'standard') notes.push('The browser reported the standard Gamepad mapping; RetroArch sees raw driver button numbers, which differ. Re-record on a raw-mapped browser or fix numbers by hand.');
    L.push(`input_driver = "${o.driver}"`, `input_device = "${name}"`, `input_device_display_name = "${name}"`, `input_vendor_id = "${vid === null ? 0 : vid}"`, `input_product_id = "${pid === null ? 0 : pid}"`, '');
    const labels = [];
    const emit = (role, id, label, axisPreferred) => {
      let m;
      if ((m = /^gp:b(\d+)$/.exec(id))) { L.push(`input_${role}_btn = "${m[1]}"`); labels.push(`input_${role}_btn_label = "${label}"`); }
      else if ((m = /^gp:a(\d+)([+-])$/.exec(id))) { L.push(`input_${role}_axis = "${m[2]}${m[1]}"`); labels.push(`input_${role}_axis_label = "${label}"`); }
      else if (id) notes.push(`${label}: ${id} is not a gamepad button/axis, skipped`);
      void axisPreferred;
    };
    for (const [role, phys, label] of RA_ROLES) { const s = raSource(p, phys); if (s) emit(role, s, label); }
    // rotary / trackball exposed as gamepad axes feed the analog sticks
    const axis = (stick, id, label) => { const m = /^gp:a(\d+)$/.exec(id || ''); if (m) { L.push(`input_${stick}_plus_axis = "+${m[1]}"`, `input_${stick}_minus_axis = "-${m[1]}"`); labels.push(`input_${stick}_plus_axis_label = "${label} +"`, `input_${stick}_minus_axis_label = "${label} -"`); } else if (id) notes.push(`${label}: ${id} is not a gamepad axis, skipped (a mouse-like trackball/spinner is handled by RetroArch's mouse device, not by autoconfig)`); };
    axis('l_x', first(ctl(p, 'SPINNER').length ? ctl(p, 'SPINNER') : p.spinner.enabled ? p.spinner.source : p.paddle.source), 'Spinner');
    axis('r_x', first(ctl(p, 'TRACKBALL_X').length ? ctl(p, 'TRACKBALL_X') : p.trackball.x), 'Trackball X');
    axis('r_y', first(ctl(p, 'TRACKBALL_Y').length ? ctl(p, 'TRACKBALL_Y') : p.trackball.y), 'Trackball Y');
    L.push('', ...labels, '');
    notes.push('Keypad 0-9 * # cannot be expressed in an autoconfig file (RetroPad has no such buttons); use the keyboard mapper in a core remap.');
    return { filename: slug(p.name) + '-retroarch.cfg', text: L.join('\n'), notes, mime: 'text/plain', hint: 'Put it in the RetroArch autoconfig folder (joypad driver subfolder, e.g. autoconfig/udev). The input_driver line must match your driver.' };
  }

  // ---- RetroArch core remap .rmap ----
  function retroarchRmap(p, opts) {
    const o = Object.assign({ player: 1 }, opts), n = o.player, notes = [];
    const L = [`# ${BANNER}`, '# Core input remap (RetroArch input_remapping_save_file format: input_libretro_device_pN, input_playerN_analog_dpad_mode, input_remap_port_pN, input_playerN_btn_*).',
      `# RETRO_DEVICE_JOYPAD = 1, RETRO_DEVICE_MOUSE = 2, RETRO_DEVICE_ANALOG = 5 (libretro.h).`,
      `input_libretro_device_p${n} = "1"`, `input_player${n}_analog_dpad_mode = "0"`, `input_remap_port_p${n} = "${n - 1}"`];
    if (p.trackball.enabled) { const tp = p.trackball.port; L.push(`# Trackball as a mouse device on port ${tp}; enable only if the core accepts RETRO_DEVICE_MOUSE there:`, `# input_libretro_device_p${tp} = "2"`, `# input_remap_port_p${tp} = "${tp - 1}"`); }
    notes.push('Core-specific: which RetroPad button the Atari core treats as fire (and whether it offers a mouse/paddle device) was not verified; the file only sets the device type, port and d-pad mode.');
    L.push('');
    return { filename: slug(p.name) + '-retroarch.rmap', text: L.join('\n'), notes, mime: 'text/plain', hint: 'Save into RetroArch\'s remaps/<core name>/ folder.' };
  }

  // ---- SDL gamecontrollerdb ----
  const hex2 = (v) => (v & 255).toString(16).padStart(2, '0') + ((v >> 8) & 255).toString(16).padStart(2, '0');
  // SDL2/SDL3 USB joystick GUID: bus 0003, crc 0000 (mappings never include the CRC), vendor, product, version, as little-endian 16-bit words.
  function sdlGuid(vid, pid, version, bus) {
    return (hex2(bus || 3) + '0000' + hex2(vid || 0) + '0000' + hex2(pid || 0) + '0000' + hex2(version || 0) + '0000');
  }
  const SDL_ROLES = [['a', 'A'], ['b', 'B'], ['x', 'X'], ['y', 'Y'], ['leftshoulder', 'L1'], ['rightshoulder', 'R1'], ['lefttrigger', 'L2'], ['righttrigger', 'R2'],
    ['back', 'SELECT'], ['start', 'START'], ['guide', 'MENU'], ['misc1', 'CREDIT'], ['misc2', 'SETTINGS'], ['dpup', 'DPAD_UP'], ['dpdown', 'DPAD_DOWN'], ['dpleft', 'DPAD_LEFT'], ['dpright', 'DPAD_RIGHT']];
  function sdl(p, opts) {
    const o = Object.assign({ platform: 'Linux' }, opts), notes = [], parts = [];
    const vid = p.device.vendorId, pid = p.device.productId;
    const name = (p.device.name || 'Atari Gamestation Gamepad').replace(/[,\r\n]/g, ' ');
    const val = (id, axisRole) => {
      let m;
      if ((m = /^gp:b(\d+)$/.exec(id))) return 'b' + m[1];
      if ((m = /^gp:a(\d+)([+-])$/.exec(id))) return m[2] + 'a' + m[1];
      if (axisRole && (m = /^gp:a(\d+)$/.exec(id))) return 'a' + m[1];
      return null;
    };
    for (const [role, phys] of SDL_ROLES) {
      const s = raSource(p, phys), v = s && val(s, false);
      if (v) parts.push(`${role}:${v}`); else if (s) notes.push(`${phys}: ${s} is not a gamepad button/axis, skipped`);
    }
    [['leftx', first(ctl(p, 'SPINNER').length ? ctl(p, 'SPINNER') : p.spinner.enabled ? p.spinner.source : p.paddle.source)], ['rightx', first(ctl(p, 'TRACKBALL_X').length ? ctl(p, 'TRACKBALL_X') : p.trackball.x)], ['righty', first(ctl(p, 'TRACKBALL_Y').length ? ctl(p, 'TRACKBALL_Y') : p.trackball.y)]].forEach(([role, id]) => {
      const v = id && val(id, true); if (v) parts.push(`${role}:${v}`); else if (id) notes.push(`${role}: ${id} is not a gamepad axis, skipped`);
    });
    if (vid === null || pid === null) notes.push('vendor/product id unknown: GUID is a placeholder and must be replaced');
    if (p.device.mapping === 'standard') notes.push('The browser reported the standard Gamepad mapping; SDL numbers buttons by the raw driver order, so indices may differ.');
    notes.push('Keypad 0-9 * # and the mouse-like trackball are not part of the SDL gamepad model.');
    const line = `${sdlGuid(vid, pid, 0, 3)},${name},${parts.join(',')},platform:${o.platform},`;
    const text = `# ${BANNER}\n${vid === null || pid === null ? '# GUID below is a placeholder (vendor/product unknown).\n' : ''}${line}\n`;
    return { filename: slug(p.name) + '-gamecontrollerdb.txt', text, line, notes, mime: 'text/plain', hint: 'Append to gamecontrollerdb.txt or set SDL_GAMECONTROLLERCONFIG to the line (SDL2 and SDL3, v2.0.10+).' };
  }

  return { BANNER, mame, retroarchCfg, retroarchRmap, sdl, sdlGuid, mameKey, slug };
});
