// ACWriter PAGE mode (hmode 4) in the emulator. Screenshots: out/acw-page-<model>-N.png
const { chromium } = require('C:/Users/raver/craftapi/node_modules/playwright-core');
const fs = require('fs');
const ROOT = 'C:/Users/raver/ataricraft';
const MODEL = process.argv[2] || '130xe';
let TEXT = 'alpha beta gamma\rDelta epsilon zeta\rEta theta iota\r';
for (let i = 4; i <= 12; i++) TEXT += 'line number ' + i + ' filler text that is long enough to need wrapping in the page view at ten characters per inch\r';
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const p = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file:///' + ROOT + '/web/index.html');
  await p.setInputFiles('#romfiles', [ROOT + '/software_n_roms/ATARIXL.ROM', ROOT + '/software_n_roms/ATARIBAS.ROM']);
  await p.selectOption('#model', MODEL).catch(() => {});
  await p.selectOption('#ram', MODEL === '130xe' ? '128' : '64').catch(() => {});
  await p.click('#boot'); await p.waitForTimeout(3000);
  const bytes = Array.from(fs.readFileSync(ROOT + '/tools/acwriter/poc5.xex'));
  await p.evaluate((a) => FujiNet.emu.bootFile('POC.XEX', new Uint8Array(a)), bytes);
  await p.waitForTimeout(3000);
  await p.locator('canvas').first().click();
  await p.waitForTimeout(10000); await p.keyboard.press('Escape'); await p.waitForTimeout(1500);
  await p.evaluate((t) => FujiNet.emu.hostWrite('ED.TXT', new Uint8Array([...t].map((c) => c.charCodeAt(0) === 13 ? 155 : c.charCodeAt(0)))), TEXT);
  const key = async (k, w = 900) => { await p.keyboard.press(k); await p.waitForTimeout(w); };
  const type = async (s) => { for (const ch of s) await key(ch === ' ' ? 'Space' : ch === ':' ? 'Shift+Semicolon' : ch === '.' ? 'Period' : ch, 800); };
  const shot = (n) => p.locator('canvas').first().screenshot({ path: ROOT + '/out/acw-page-' + MODEL + '-' + n + '.png' });
  const menu = async (...ks) => { await key('Escape'); for (const k of ks) await key(k, 700); await p.waitForTimeout(1200); };
  const peek = (a, n = 1) => p.evaluate(([x, m]) => Array.from(ataricraft.peek(x, m)), [a, n]);
  const doc = async (n = 600) => { const a = await peek(0x6600, n); return String.fromCharCode(...a.map((c) => c === 13 || c === 14 ? 124 : c < 32 ? 94 : c)); };
  let fails = 0;
  const check = (name, ok, extra) => { if (!ok) fails++; console.log(ok ? 'ok  ' : 'FAIL', name, extra === undefined ? '' : JSON.stringify(extra)); };
  const hmode = async () => (await peek(0x1330))[0];
  await key('ArrowDown', 900);
  await menu('f', 'o'); await type('h:ed.txt'); await key('Enter', 2500);
  check('file loaded', (await doc()).startsWith('alpha beta gamma'));
  await shot('0-old-view');
  const before = await doc(900);
  await menu('l', 'v'); await p.waitForTimeout(2000);
  check('PAGE mode entered', (await hmode()) === 4, await hmode()); await shot('1-page');
  await key('ArrowDown', 1500); await key('ArrowRight', 1500); await shot('2-moved');
  await key('Tab', 1500); await shot('3-tab');
  for (const c of 'ab') await key(c, 1500);
  await shot('4-typed');
  await p.evaluate(() => { for (const t of ['keydown', 'keyup']) document.dispatchEvent(new KeyboardEvent(t, { code: 'IntlBackslash', key: '\\\\', bubbles: true })); }); await p.waitForTimeout(1500);
  const typed = await doc(900); const norm = (s) => s.replace(/[| ]/g, '').slice(0, 800); const same = async () => norm(await doc(900)) === norm(typed);
  check('typing/backspace edit the document', typed !== before && typed.includes('a') , typed.slice(0, 60));
  await menu('l', 'p'); await p.waitForTimeout(1500); await shot('5-a4');
  check('paper change keeps the text (soft wraps may move)', await same(), await doc(120));
  await menu('l', 't'); await p.waitForTimeout(1500); await shot('6-12cpi');
  await menu('l', 't'); await p.waitForTimeout(1500); await shot('7-17cpi');
  check('pitch change keeps the text', await same(), await doc(120));
  await menu('l', '2'); await p.waitForTimeout(1500); await shot('7b-tab');
  check('tab stop keeps the text', await same(), await doc(120));
  // page setup round trip through the CRFT trailer (paper A4, 17 cpi, one centre tab)
  const D = require('../tools/craftdoc.cjs');
  const setup = async () => ({ pap: (await peek(0x13E9))[0], pit: (await peek(0x13EA))[0], lm: (await peek(0x13EB))[0], rm: (await peek(0x13EC))[0], nt: (await peek(0x13F3))[0], tp: (await peek(0x14E8))[0], tk: (await peek(0x14F0))[0] });
  const s0 = await setup(); console.log('setup before save', JSON.stringify(s0));
  await menu('f', 'a'); await type('h:pg.cwd'); await key('Enter', 3000);
  const files = await p.evaluate(() => Object.fromEntries(Object.entries(FujiNet.emu.hostFiles()).map(([k, v]) => [k, Array.from(v)])));
  const fk = Object.keys(files).find((k) => /^PG\.CWD$/i.test(k));
  check('PG.CWD saved on H:', !!fk);
  if (fk) {
    const pg = D.parse(Buffer.from(files[fk])).h.page;
    check('saved file carries the page trailer', !!pg && pg.paper === 'a4' && pg.pitch === 17 && pg.tabs.length === s0.nt && (s0.nt === 0 || pg.tabs[0].kind === 'c'), pg);
  }
  await menu('l', 'x'); await menu('l', 't'); await menu('l', 'p'); await menu('l', 'p');
  check('setup changed before reload', JSON.stringify(await setup()) !== JSON.stringify(s0), await setup());
  await menu('f', 'o'); await type('h:pg.cwd'); await key('Enter', 3000);
  const s1 = await setup();
  check('open restores paper, pitch, margins and tab stops', JSON.stringify(s1) === JSON.stringify(s0), [s0, s1]);
  await shot('9-reloaded');
  await menu('l', 'v'); await p.waitForTimeout(2500);
  check('left PAGE mode', (await hmode()) === 0, await hmode()); await shot('8-back');
  check('document intact after leaving', await same());
  console.log('fails:', fails, 'errors:', errs);
  await b.close();
})();
