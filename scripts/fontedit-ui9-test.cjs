// Font pull-downs and keyboard browsing (header Family > Style > Size, Fonts list, chooser): Up/Down/PageUp/PageDown/Home/End/type-to-find, Enter keeps, Esc goes back.
const { chromium } = require('C:/Users/raver/craftapi/node_modules/playwright-core');
const path = require('path'), fs = require('fs');
const URL = 'file:///' + path.resolve(__dirname, '..', 'web', 'fontedit.html').replace(/\\/g, '/');
let fails = 0;
const ok = (c, m) => { console.log((c ? 'ok  ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const pg = await (await b.newContext({ viewport: { width: 1600, height: 900 } })).newPage(); const errs = [];
  pg.on('pageerror', (e) => errs.push(e.message)); pg.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await pg.goto(URL); await pg.waitForTimeout(600);
  const fonts = ['arial', 'cour', 'consola', 'times'].map((n) => 'C:/Windows/Fonts/' + n + '.ttf').filter((f) => fs.existsSync(f));
  await pg.setInputFiles('#file', fonts); await pg.waitForTimeout(2500);
  const ent = () => pg.evaluate(() => FE.state.entry);
  ok(await pg.locator('#hfam option').count() >= 3, 'header pull-down lists fonts: ' + await pg.locator('#hfam option').count());
  ok(await pg.locator('#hsize option').count() >= 13, 'size pull-down lists sizes: ' + await pg.locator('#hsize option').count());
  ok((await pg.locator('#hstyle option').count()) >= 1, 'style pull-down present');
  await pg.evaluate(() => FE.openEntry('craft')); await pg.waitForTimeout(300);
  await pg.focus('#hfam'); const start = await ent();
  await pg.keyboard.press('ArrowDown'); await pg.waitForTimeout(700);
  const second = await ent(); ok(second !== start, 'pull-down ArrowDown loads next font: ' + start + ' -> ' + second);
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(700); ok(await ent() === start, 'Esc in the pull-down goes back to ' + start);
  await pg.keyboard.press('ArrowDown'); await pg.waitForTimeout(500); await pg.keyboard.press('Enter'); await pg.waitForTimeout(400);
  ok(await ent() === second, 'Enter keeps the font');
  await pg.evaluate(() => FE.openEntry('craft')); await pg.waitForTimeout(300);
  await pg.selectOption('#hsize', '18'); await pg.waitForTimeout(300); ok(await pg.evaluate(() => FE.state.f.adv) === 18, 'size pull-down selects Craft 18 px');
  await pg.selectOption('#hsize', '26'); await pg.waitForTimeout(300); ok(await pg.evaluate(() => FE.state.f.adv) === 26, 'size pull-down selects Craft 26 px');
  await pg.evaluate(() => FE.openEntry('craft')); await pg.waitForTimeout(300);
  await pg.focus('#flist .fitem[data-fid="craft"]');
  const ids = await pg.evaluate(() => [...document.querySelectorAll('#flist .fitem')].map((x) => x.dataset.fid));
  await pg.keyboard.press('ArrowDown'); await pg.waitForTimeout(700); ok(await ent() === ids[1], 'list ArrowDown loads next font ' + ids[1]);
  ok(await pg.evaluate(() => document.activeElement.classList.contains('fitem')), 'focus stays in the list');
  await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('ArrowUp'); await pg.waitForTimeout(700); ok(await ent() === ids[1], 'down+up lands on the same font');
  await pg.keyboard.press('End'); await pg.waitForTimeout(900); ok(await ent() === ids[ids.length - 1], 'End = last font');
  await pg.keyboard.press('Home'); await pg.waitForTimeout(900); ok(await ent() === ids[0], 'Home = first font');
  await pg.keyboard.press('PageDown'); await pg.waitForTimeout(900); ok(await ent() === ids[Math.min(8, ids.length - 1)], 'PageDown moves 8');
  await pg.keyboard.type('zf'); await pg.waitForTimeout(800); ok((await ent()) === 'zfont', 'type-to-find "zf" -> zfont');
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(800);
  ok(await ent() !== 'zfont', 'Esc in the list goes back to where browsing started: ' + await ent());
  await pg.evaluate(() => FE.openEntry('craft')); await pg.waitForTimeout(300);
  await pg.click('#bchoose'); await pg.waitForSelector('#chooser:not([hidden])'); await pg.waitForTimeout(500);
  await pg.keyboard.press('ArrowDown'); await pg.waitForTimeout(700);
  const live = await ent(); ok(live !== 'craft', 'chooser ArrowDown previews/loads the next font: ' + live);
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(900); ok(await ent() === 'craft', 'chooser Esc cancels and returns to Craft Sans');
  await pg.click('#bchoose'); await pg.waitForTimeout(400); await pg.keyboard.press('ArrowDown'); await pg.waitForTimeout(500); await pg.keyboard.press('Enter'); await pg.waitForTimeout(700);
  ok(await ent() !== 'craft' && await pg.locator('#chooser').isHidden(), 'chooser Enter keeps the highlighted font');
  await pg.screenshot({ path: 'out/picker-1600.png' });
  await pg.setViewportSize({ width: 760, height: 800 }); await pg.waitForTimeout(300); await pg.screenshot({ path: 'out/picker-760.png' });
  ok(errs.length === 0, 'no console errors ' + errs.slice(0, 3).join('|'));
  await b.close(); process.exit(fails ? 1 : 0);
})();
