// Workbench Images tab in a real browser: add files, group by type, filter, convert, download. node scripts/img-test.cjs
const { chromium } = require('C:/Users/raver/craftapi/node_modules/playwright-core');
const fs = require('fs'), os = require('os'), path = require('path'), zlib = require('zlib');
const { spawnSync } = require('child_process');
global.window = global; require('../web/js/palette.js');
const I = require('../web/js/imgconv.js');
const ROOT = 'C:/Users/raver/ataricraft';
let bad = 0;
const ok = (c, m) => { if (!c) { bad++; console.log('FAIL', m); } else console.log('ok  ', m); };
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'imgui-'));
  const w = 64, h = 48, d = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) d.set([x * 4, y * 5, 120, 255], (y * w + x) * 4);
  const g = { w, h, data: d };
  const png = I.encodePNG(g, { deflate: (b) => zlib.deflateSync(Buffer.from(b)) });
  fs.writeFileSync(path.join(tmp, 'a.png'), png); fs.writeFileSync(path.join(tmp, 'b.png'), png); fs.writeFileSync(path.join(tmp, 'c.bmp'), I.encodeBMP(g));
  fs.writeFileSync(path.join(tmp, 'pic.mic'), I.encodeAtari(g, 'gr15', {})); fs.writeFileSync(path.join(tmp, 'notes.txt'), 'hello');
  const hasFF = spawnSync('ffmpeg', ['-version']).status === 0;
  if (hasFF) spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', path.join(tmp, 'a.png'), path.join(tmp, 'd.jpg')]);
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const p = await (await b.newContext({ acceptDownloads: true })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file:///' + ROOT + '/web/workbench.html');
  await p.click('button[data-t="images"]');
  await p.setInputFiles('#imfiles', fs.readdirSync(tmp).map((n) => path.join(tmp, n)));
  await p.waitForFunction((n) => document.querySelectorAll('#imtab tr[data-i]').length === n, hasFF ? 5 : 4, { timeout: 15000 });
  const badges = await p.$$eval('#imtypes button', (bs) => bs.map((x) => x.textContent.replace(/\s+/g, ' ').trim()));
  console.log(badges.join(' | '));
  ok(badges.some((x) => /^PNG 2$/.test(x)) && badges.some((x) => /^BMP 1$/.test(x)) && badges.some((x) => /^Atari 1$/.test(x)), 'type badges count files');
  ok(/skipped/.test(await p.textContent('#imstat')), 'non-image skipped');
  ok(await p.$$eval('#imtab img', (a) => a.length >= 4), 'thumbnails drawn');
  await p.selectOption('#imfilter', 'png');
  ok((await p.$$('#imtab tr[data-i]')).length === 2, 'filter by type');
  await p.selectOption('#imfilter', '');
  await p.click('#imnone');
  await p.$$eval('#imtab tr[data-i]', (rows) => rows.filter((r) => /a\.png/.test(r.textContent))[0].querySelector('input').click());
  await p.selectOption('#imto', 'gr15');
  let [dl] = await Promise.all([p.waitForEvent('download'), p.click('#imconv')]);
  let f = path.join(tmp, 'dl1'); await dl.saveAs(f);
  ok(dl.suggestedFilename() === 'a.mic' && fs.statSync(f).size === 7680, 'PNG to GR.15 download is 7680 bytes named a.mic');
  await p.selectOption('#imto', 'png');
  await p.click('#imall');
  [dl] = await Promise.all([p.waitForEvent('download'), p.click('#imconv')]);
  f = path.join(tmp, 'dl2.zip'); await dl.saveAs(f);
  const py = spawnSync('python', ['-c', "import zipfile,sys;z=zipfile.ZipFile(sys.argv[1]);print(z.testzip(),sorted(z.namelist()))", f]);
  console.log(py.stdout.toString().trim());
  ok(/None/.test(py.stdout.toString()) && /a\.png/.test(py.stdout.toString()) && /pic\.png/.test(py.stdout.toString()), 'multi convert downloads a valid ZIP');
  if (hasFF) {
    await p.selectOption('#imfilter', 'jpg'); await p.selectOption('#imto', 'webp');
    [dl] = await Promise.all([p.waitForEvent('download'), p.click('#imall').then(() => p.click('#imconv'))]);
    f = path.join(tmp, 'dl3'); await dl.saveAs(f);
    ok(I.detect(fs.readFileSync(f)) === 'webp', 'JPEG to WebP through the browser codec');
  }
  await p.selectOption('#imfilter', ''); await p.click('#imall');
  [dl] = await Promise.all([p.waitForEvent('download'), p.click('#imorg')]);
  f = path.join(tmp, 'dl4.zip'); await dl.saveAs(f);
  const py2 = spawnSync('python', ['-c', "import zipfile,sys;z=zipfile.ZipFile(sys.argv[1]);print(z.testzip(),sorted(z.namelist()))", f]);
  console.log(py2.stdout.toString().trim());
  ok(/PNG\/a\.png/.test(py2.stdout) && /BMP\/c\.bmp/.test(py2.stdout) && /Atari-GR15\/pic\.mic/.test(py2.stdout), 'organized ZIP has a folder per type');
  ok(!errs.length, 'no page errors ' + errs.join(';'));
  await b.close(); fs.rmSync(tmp, { recursive: true, force: true });
  console.log(bad ? bad + ' FAILED' : 'all passed'); process.exit(bad ? 1 : 0);
})();
