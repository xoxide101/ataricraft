// Builds web/js/titles-data.js from MAME hash XML files (https://github.com/mamedev/mame/tree/master/hash).
// usage: node scripts/gen-titles.cjs <dir containing a800.xml, a800_flop.xml, a800_cass.xml, a5200.xml>
const fs = require('fs');
const dir = process.argv[2] || 'C:/Users/raver/ataricraft/out/xml';
const dec = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'");
const T = {};
for (const f of ['a800', 'a800_flop', 'a800_cass', 'a5200']) {
  const p = `${dir}/${f}.xml`;
  if (!fs.existsSync(p)) continue;
  const x = fs.readFileSync(p, 'utf8');
  for (const m of x.matchAll(/<software\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/software>/g)) {
    const d = /<description>([\s\S]*?)<\/description>/.exec(m[2]);
    if (!d) continue;
    const y = /<year>([^<]*)<\/year>/.exec(m[2]), pub = /<publisher>([^<]*)<\/publisher>/.exec(m[2]);
    const extra = [y && y[1] !== '????' ? y[1] : '', pub && !/unknown/i.test(dec(pub[1])) ? dec(pub[1]) : ''].filter(Boolean).join(', ');
    const key = m[1].toLowerCase();
    if (!T[key]) T[key] = dec(d[1]) + (extra ? ` (${extra})` : '');
  }
}
fs.writeFileSync('C:/Users/raver/ataricraft/web/js/titles-data.js', '// Generated by scripts/gen-titles.cjs from the MAME software lists (a800, a800_flop, a800_cass, a5200).\nwindow.AC = window.AC || {};\nAC.TITLES_BUILTIN = ' + JSON.stringify(T) + ';\n');
console.log(Object.keys(T).length, 'titles');
