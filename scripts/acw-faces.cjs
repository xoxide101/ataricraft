// node scripts/acw-faces.cjs : regenerates the ACWriter-faces data for the font editor and the overridden .inc files in font/build/
const A = require('../tools/acwfaces.cjs');
for (const f of A.writeWeb()) console.log(f.id.padEnd(8), f.adv + ' px', f.override ? 'OVERRIDE' : 'built   ', f.src);

// The Craft family sizes 14-26 (font/craft14.acf ... craft26.acf) embedded for the font editor, which must work from file:// without fetch.
{
  const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..'), big = {};
  for (const s of [14, 16, 18, 20, 22, 24, 26]) { const p = path.join(root, 'font', 'craft' + s + '.acf'); if (fs.existsSync(p)) big[s] = fs.readFileSync(p).toString('base64'); }
  fs.writeFileSync(path.join(root, 'web', 'js', 'fontedit', 'craft-big.js'), '// GENERATED by scripts/acw-faces.cjs - Craft sizes 14-26 (font/craft*.acf), ACF2 base64.\nwindow.CRAFT_BIG = ' + JSON.stringify(big) + ';\n');
  console.log('craft-big.js', Object.keys(big).join(','));
}
